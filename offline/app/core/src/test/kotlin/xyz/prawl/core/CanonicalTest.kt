    /** Raw attacker text of one spend: exactly what the signature covers (no validation). */
    private fun rawMessage(chainId: String, escrow: String, coinId: String, expiry: String, depth: Int, parent: String, outs: List<Pair<String, String>>) =
        "PRAWL-OTK-v3|$chainId|$escrow|$coinId|$expiry|$depth|$parent|${Bytes.sha256Hex(outs.joinToString(";") { "${it.first}:${it.second}" })}"

    private class Forged(val bundle: JsonObject, val messageVerifiesOverRawText: Boolean)

    /**
     * Mallory (software key, hardware modelled by FakeKeyVault) signs the genesis spend of her coin over text she formats herself.
     * [hdr] overrides header strings; [outs] are the raw (value, key) strings; the first goes to Bob's real key.
     * [sigMangle] may re-encode the DER signature.
     */
    private fun forge(mallory: OfflineWallet, coin: Note, bobReq: ReceiveRequest, hdr: Map<String, JsonPrimitive> = emptyMap(),
                      siblings: List<Pair<String, String>> = listOf("100000000000000000" to hex32()), bobValue: String? = null,
                      indexRaw: JsonPrimitive = JsonPrimitive(0), sigMangle: (ByteArray) -> ByteArray = { it }): Forged {
        bobReq.certs.forEach { (_, v) -> mallory.certStore.put(Bytes.unb64((v as JsonPrimitive).content)) }   // as pay() does
        val h0 = coin.header.json
        val header = JsonObject(LinkedHashMap(h0).also { m -> hdr.forEach { (k, v) -> m[k] = v } })
        val bobKey = mallory.certs.leafKeyHash(bobReq.chain, bobReq.certs)
        val total = coin.value
        val sibTotal = siblings.fold(BigInteger.ZERO) { a, s -> a + BigInteger(s.first.trimStart('+').ifEmpty { "0" }) }
        val bobVal = bobValue ?: (total - sibTotal).toString()
        val outs = listOf(bobVal to bobKey) + siblings
        val text = rawMessage((header["chainId"] as JsonPrimitive).content, (header["escrow"] as JsonPrimitive).content, (header["coinId"] as JsonPrimitive).content,
            (header["expiry"] as JsonPrimitive).content, 0, coin.noteId, outs)
        val der = mallory.keys.sign(coin.alias, text.toByteArray(), null, ApprovalPrompt("t", ""))
        val sg = Signature.getInstance("SHA256withECDSA").apply { initVerify(mallory.certs.leafKey(coin.header.k0)); update(text.toByteArray()) }
        val verifies = sg.verify(der)
        val spend = buildJsonObject {
            put("outputs", JsonArray(outs.map { buildJsonObject { put("value", it.first); put("key", it.second) } }))
            put("index", indexRaw); put("sig", Bytes.b64(sigMangle(der))); put("next", bobReq.json["chain"]!!)
        }
        val b = buildJsonObject { put("header", header); put("path", JsonArray(listOf(spend))) }
        return Forged(mallory.carry(b, bobReq, withDepositProof = false), verifies)
    }

    private fun scenario(eth: String = "0.5"): Triple<OfflineWallet, Note, OfflineWallet> {
