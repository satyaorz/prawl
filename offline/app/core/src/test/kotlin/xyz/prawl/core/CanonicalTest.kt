    @Test fun messagesEqualTheEscrowFixtures() {
        var compared = 0; var refused = 0
        for (f in listOf("fixtures/v3_phone.json", "fixtures/v3_synthetic.json")) {
            val d = Js.parse(File(v3, "escrow_v3/$f").readText())
            for ((name, r) in d.obj("redeems")) {
                r as JsonObject
                val c = d.obj("coins").obj(r.str("coin"))
                val h = CoinHeader(buildJsonObject {
                    put("v", 3); put("chainId", c["chainId"]!!.let { (it as JsonPrimitive).content }); put("escrow", c.str("escrow").removePrefix("0x"))
                    put("coinId", c.str("coinId").removePrefix("0x")); put("expiry", (c["expiry"] as JsonPrimitive).content.toLong())
                    put("value", c.str("value")); put("depositor", c.str("depositor").removePrefix("0x"))
                })
                val entries = r.arr("path").objects() + r.obj("redeem")
                for ((depth, e) in entries.withIndex()) {
                    val outs = e.arr("values").map { (it as JsonPrimitive).content }.zip(e.arr("keyHashes").map { (it as JsonPrimitive).content.removePrefix("0x") })
                        .map { (v, k) -> Output(BigInteger(v), k) }
                    val want = Bytes.unhex(e.str("message"))
                    if (outs.any { it.value.signum() <= 0 } || outs.size > Protocol.MAX_OUTPUTS) {
                        assertThrows { Protocol.spendMessage(h, depth, e.str("noteId").removePrefix("0x"), outs) }; refused++
                    } else {
                        val got = Protocol.spendMessage(h, depth, e.str("noteId").removePrefix("0x"), outs)
                        assertEquals("$f $name depth $depth", String(want), String(got)); compared++
                    }
                }
            }
        }
        println("conformance: $compared messages equal the escrow's bytes; $refused invalid ones refused")
        assertTrue("compared $compared", compared >= 120)
    }

