        // long-form sequence length
        assertFalse("long-form length", EcdsaDer.isCanonical(byteArrayOf(0x30, 0x81.toByte(), sig[1]) + sig.copyOfRange(2, sig.size)))
        assertFalse(EcdsaDer.isCanonical(ByteArray(0))); assertFalse(EcdsaDer.isCanonical(ByteArray(70)))
    }

