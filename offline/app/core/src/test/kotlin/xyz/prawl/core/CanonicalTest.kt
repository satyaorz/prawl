/**
 * Audit F1 (non-canonical text) and F2 (output fan-out), wallet side.
 *
 *  - Conformance: the wallet's message equals the escrow's `spendMessage()` byte for byte, against the fixtures generated by
 *    `escrow_v3/tools/prawl_v3.py spend_message` (which the escrow's Foundry tests assert equal the contract's output).
 *  - The attack, modelled: an attacker signs a validly-signed bundle whose TEXT is spelled differently from what the escrow can
