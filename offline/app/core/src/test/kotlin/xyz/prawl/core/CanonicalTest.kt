    /**
     * THE ATTACK (audit PoCs Audit01*): the signature is valid over the text the wallet would rebuild from the raw strings,
     * but the escrow can only rebuild the canonical spelling, so `redeem` would fail with BadSig forever. Every spelling must be refused.
     */
    @Test fun nonCanonicalSpellingsAreRefusedEvenWhenTheSignatureVerifies() {
        val upperSibling = hex32().uppercase()
        val cases: List<Triple<String, (Note) -> Map<String, JsonPrimitive>, List<Pair<String, String>>?>> = listOf(
            Triple("uppercase sibling output key", { _ -> emptyMap() }, listOf("100000000000000000" to upperSibling)),
            Triple("0x-prefixed sibling output key", { _ -> emptyMap() }, listOf("100000000000000000" to "0x" + hex32())),
            Triple("sibling key of the wrong length", { _ -> emptyMap() }, listOf("100000000000000000" to hex32().drop(2))),
            Triple("uppercase coinId", { n -> mapOf("coinId" to JsonPrimitive(n.header.coinId.uppercase())) }, null),
            Triple("0x-prefixed escrow", { n -> mapOf("escrow" to JsonPrimitive("0x" + n.header.escrow)) }, null),
            Triple("uppercase escrow", { n -> mapOf("escrow" to JsonPrimitive(n.header.escrow.uppercase())) }, null),
            Triple("EIP-55 escrow", { n -> mapOf("escrow" to JsonPrimitive(Eth.checksum(n.header.escrow))) }, null),
            Triple("chainId with leading zeros", { _ -> mapOf("chainId" to JsonPrimitive("0011155111")) }, null),
            Triple("sibling value with a leading zero", { _ -> emptyMap() }, listOf("0100000000000000000" to hex32())),
            Triple("expiry with a leading zero", { n -> mapOf("expiry" to JsonPrimitive("0" + n.header.expiry)) }, null),
        )
        for ((what, hdr, sibs) in cases) {
            val (mallory, coin, bob) = scenario()
            val req = bob.request("b")
            val f = if (sibs != null) forge(mallory, coin, req, siblings = sibs) else forge(mallory, coin, req, hdr = hdr(coin))
            assertTrue("$what: the signature is valid over the wallet's rebuilt text (this is the real attack)", f.messageVerifiesOverRawText)
            val rep = accept(f, bob, "b")
            assertFalse("$what must be refused", rep.accepted)
            assertTrue("$what: refused for non-canonical text, not by accident: ${rep.fails}", rep.fails.any { it.startsWith("non-canonical text in the signed message") })
            assertFalse("$what: the first failing line is the canonical gate", rep.lines.first { !it.ok }.title != "Canonical text")
            assertTrue("$what: Bob holds nothing", bob.spendable().isEmpty())
            assertNotNullPending(bob, "b")      // his receive key stays pending: nothing was consumed
        }
    }

    private fun assertNotNullPending(w: OfflineWallet, name: String) = assertTrue(w.notes.pendingChain(name) != null)

    /** Fields the wallet re-canonicalises itself (value, index, expiry spelling) and the signature encoding are still refused by the gate. */
    @Test fun nonCanonicalJsonFieldsAreRefusedEvenIfTheSignedTextIsCanonical() {
        fun refused(what: String, build: (OfflineWallet, Note, ReceiveRequest) -> Forged) {
            val (mallory, coin, bob) = scenario(); val req = bob.request("b")
            val rep = accept(build(mallory, coin, req), bob, "b")
            assertFalse("$what must be refused", rep.accepted)
            assertTrue("$what: ${rep.fails}", rep.fails.any { it.startsWith("non-canonical text in the signed message") })
        }
        refused("signed value written with '+'") { m, c, r -> repack(forge(m, c, r), "value", "+") }
        refused("index as a string with a leading zero") { m, c, r -> forge(m, c, r, indexRaw = JsonPrimitive("00")) }
        refused("index out of range") { m, c, r -> forge(m, c, r, indexRaw = JsonPrimitive(7)) }
        refused("expiry as a float") { m, c, r -> forge(m, c, r, hdr = mapOf("expiry" to JsonPrimitive(c.header.expiry.toString() + ".0"))) }
        refused("signature with a padded integer") { m, c, r -> forge(m, c, r, sigMangle = { s -> padR(s) }) }
        refused("signature with a trailing byte") { m, c, r -> forge(m, c, r, sigMangle = { s -> s + 0.toByte() }) }
        refused("header value with a leading zero") { m, c, r -> forge(m, c, r, hdr = mapOf("value" to JsonPrimitive("0" + c.value))) }
    }

    /** Re-spells the first output value with a prefix (the signed text keeps the canonical spelling: only the JSON differs). */
    private fun repack(f: Forged, field: String, prefix: String): Forged {
        val p = f.bundle.arr("path").objects()[0]
        val outs = p.arr("outputs").objects().toMutableList()
        outs[0] = outs[0].with(field, if (prefix == "+") "+" + outs[0].str(field).trimStart('+') else outs[0].str(field))
        return Forged(f.bundle.with("path", JsonArray(listOf(p.with("outputs", JsonArray(outs))))), f.messageVerifiesOverRawText)
    }

    private fun padR(sig: ByteArray): ByteArray {
        val rLen = sig[3].toInt()
        return byteArrayOf(0x30, (sig[1] + 1).toByte(), 0x02, (rLen + 1).toByte(), 0x00) + sig.copyOfRange(4, sig.size)
    }

