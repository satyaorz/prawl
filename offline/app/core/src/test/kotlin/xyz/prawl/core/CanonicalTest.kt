    @Test fun strictDer() {
        // every real phone / harness signature is canonical
        var n = 0
        for (dir in listOf(Vectors.split, Vectors.e2e, Vectors.ho)) for (f in dir.listFiles()!!.filter { it.name.startsWith("pay3_") || it.name.startsWith("redeem3_") }) {
