        }
        assertTrue(n > 10)
        val sig = Bytes.unb64(Js.parse(File(Vectors.split, "pay3_s_bob1.json").readText()).arr("path").objects()[0].str("sig"))
        assertTrue(EcdsaDer.isCanonical(sig))
        assertFalse("trailing byte", EcdsaDer.isCanonical(sig + 0.toByte()))
        assertFalse("truncated", EcdsaDer.isCanonical(sig.copyOf(sig.size - 1)))
        // redundant leading zero in r
        val rLen = sig[3].toInt(); val padded = byteArrayOf(0x30, (sig[1] + 1).toByte(), 0x02, (rLen + 1).toByte(), 0x00) + sig.copyOfRange(4, sig.size)
